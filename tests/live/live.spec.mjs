// Checks against the live page (Phase 7). Analytics are intercepted, so running these never
// counts as plays:
//   SPELLAR_LIVE_URL=https://www.seds.ca npx playwright test --project=live

import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
import { decode } from '../../bin/lib/puzzle.mjs';

const BASE = process.env.SPELLAR_LIVE_URL;
test.skip(!BASE, 'set SPELLAR_LIVE_URL, e.g. https://www.seds.ca');

const PAGE = `${BASE}/spellar/`;
const schedule = JSON.parse(readFileSync(new URL('../../data/schedule.json', import.meta.url), 'utf8'));
const words = JSON.parse(readFileSync(new URL('../../data/words.json', import.meta.url), 'utf8'));
const pad = (n) => (n < 10 ? '0' : '') + n;
const localDate = (d) => `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`;

test.use({ timezoneId: 'America/Toronto' });

test.beforeEach(async ({ page }) => {
  await page.waitForTimeout(3000); // space the tests out: they share a small shared-hosting server
  await page.route('**/wp-json/spellar/v1/event', (r) => r.fulfill({ status: 200, contentType: 'application/json', body: '{"ok":true}' }));
});

async function open(page) {
  const errors = [];
  page.on('pageerror', (e) => errors.push(String(e)));
  page.on('console', (m) => m.type() === 'error' && errors.push(m.text()));
  await page.goto(PAGE);
  // A WordPress request on this shared host takes ~3 s, far longer when several queue up.
  await expect(page.locator('#spellar-root .sp-board')).toBeVisible({ timeout: 60_000 });
  await page.evaluate(() => document.fonts.ready);
  return errors;
}

async function play(page, list) {
  for (const w of list) {
    await page.keyboard.type(w.toLowerCase());
    await page.keyboard.press('Enter');
    await page.waitForTimeout(40);
    await expect(page.locator('#spellar-root .sp-board[aria-busy]')).toHaveCount(0, { timeout: 8000 });
  }
}

const todaysAnswer = (page) => page.evaluate(() => { const d = new Date(), p = (n) => (n < 10 ? '0' : '') + n; return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}`; }).then((d) => schedule.days[d]);

test('the page is served from the page cache and carries the puzzles for the days around today', async ({ request }) => {
  await request.get(PAGE); // make sure a saved copy exists
  const html = await (await request.get(PAGE)).text();
  expect(html).toContain('Cached page generated by WP-Super-Cache');
  const root = html.match(/<div class="spellar" id="spellar-root" data-api="https:\/\/www\.seds\.ca\/wp-json\/spellar\/v1\/" data-guesses="https:\/\/www\.seds\.ca\/wp-content\/plugins\/spellar\/data\/guesses\.txt\?ver=\d+" data-days="([^"]+)"><\/div>/);
  expect(root).not.toBeNull();
  const days = JSON.parse(root[1].replaceAll('&quot;', '"').replaceAll('&amp;', '&'));
  // Up to three consecutive dates (UTC yesterday, today, tomorrow when the copy was saved, less
  // any before the launch), each decoding to that date's word. No answer appears in plain text.
  const dates = Object.keys(days).sort();
  expect(dates.length).toBeGreaterThanOrEqual(2);
  expect(dates.length).toBeLessThanOrEqual(3);
  for (const d of dates) {
    expect(decode(days[d].answer, d)).toBe(schedule.days[d]);
    expect(html).not.toContain(schedule.days[d] + '"');
  }
  const utcToday = new Date().toISOString().slice(0, 10);
  expect(Math.abs(Date.parse(dates.at(-1)) - Date.parse(utcToday)) / 864e5).toBeLessThanOrEqual(2);
});

test('scripts: the game async in <head>; GSAP and DrawSVG deferred, in order; none combined', async ({ request }) => {
  const html = await (await request.get(PAGE)).text();
  const head = html.slice(0, html.indexOf('</head>'));
  const srcs = [...html.matchAll(/<script\b[^>]*\bsrc=['"]([^'"]+)['"][^>]*>/g)].map((m) => ({ tag: m[0], src: m[1], at: m.index }));
  const ours = srcs.filter((s) => /spellar|gsap|DrawSVG/.test(s.src));
  expect(ours.map((s) => s.src.replace(/\?.*/, '').split('/').pop())).toEqual(['spellar.js', 'gsap.min.js', 'DrawSVGPlugin.min.js']);
  const [game, gsap, draw] = ours;
  expect(game.at).toBeLessThan(head.length);
  expect(game.tag).toMatch(/\basync\b/);
  for (const s of [gsap, draw]) expect(s.tag).toMatch(/\bdefer\b/);
  for (const s of ours) {
    expect(s.tag).toContain('data-wpacu-skip'); // Asset CleanUp leaves them as WordPress printed them
    expect(s.src).toMatch(/^https:\/\//);
  }
  // And no combined file carries a copy of the game.
  for (const s of srcs.filter((x) => /asset-cleanup/.test(x.src))) {
    expect(await (await request.get(s.src)).text()).not.toContain('Spellar for seds.ca');
  }
  expect(html).toMatch(/rel="preload" href="https:[^"]+cormorant-garamond-600\.woff2" as="font"/);
  expect(head).toContain('<script id="spellar-dot">');
});

test('a first visit draws the board without asking WordPress for the puzzle', async ({ page }) => {
  const asked = [];
  page.on('request', (r) => r.url().includes('/wp-json/spellar/v1/puzzle') && asked.push(r.url()));
  const start = Date.now();
  await open(page);
  const ms = Date.now() - start;
  expect(asked).toEqual([]);
  console.log(`board visible after ${ms} ms`);
  expect(ms).toBeLessThan(6000); // usually ~1-2 s; generous for a busy shared host
});

for (const [w, h] of [[360, 640], [375, 812], [1280, 800]]) {
  test(`the game's own styles hold inside the theme and Elementor at ${w}×${h}`, async ({ page }) => {
    await page.setViewportSize({ width: w, height: h });
    const errors = await open(page);
    const s = await page.evaluate(() => {
      const css = (sel, prop) => getComputedStyle(document.querySelector(sel))[prop];
      const box = (sel) => document.querySelector(sel).getBoundingClientRect();
      return {
        tileBorder: css('#spellar-root .sp-tile', 'borderTopWidth'),
        tileBorderColor: css('#spellar-root .sp-tile', 'borderTopColor'),
        dpr: window.devicePixelRatio,
        tileRadius: css('#spellar-root .sp-tile', 'borderTopLeftRadius'),
        tileFont: css('#spellar-root .sp-tile', 'fontFamily'),
        keyBg: css('#spellar-root .sp-key', 'backgroundColor'),
        keyRadius: css('#spellar-root .sp-key', 'borderTopLeftRadius'),
        keyShadow: css('#spellar-root .sp-key', 'boxShadow'),
        keyTransform: css('#spellar-root .sp-key', 'textTransform'),
        linkBg: css('#spellar-root .sp-link', 'backgroundColor'),
        markFont: css('#spellar-root .sp-word', 'fontFamily'),
        tile: box('#spellar-root .sp-tile').width,
        keysBottom: box('#spellar-root .sp-keys').bottom,
        rootLeft: box('#spellar-root').left,
        scrollW: document.documentElement.scrollWidth,
      };
    });
    expect(errors).toEqual([]);
    // 1.5 px is drawn as 1 px on a 1× screen (Chromium snaps borders to device pixels).
    expect(s.tileBorder).toBe(s.dpr >= 2 ? '1.5px' : '1px');
    expect(s.tileBorderColor).toBe('rgb(17, 17, 17)');
    expect(s.tileRadius).toBe('0px');
    expect(s.tileFont).toMatch(/Source Sans/);
    expect(s.markFont).toMatch(/Spellar Display/);
    expect(s.keyBg).toBe('rgb(255, 255, 255)');
    expect(s.keyRadius).toBe('0px');
    expect(s.keyShadow).toBe('none');
    expect(s.linkBg).toBe('rgba(0, 0, 0, 0)');
    expect(s.scrollW).toBe(w); // no sideways scrolling
    if (w === 360) expect(s.keysBottom).toBeLessThanOrEqual(640); // 7×7 board and keyboard fit below the header
    if (w === 1280) expect(s.tile).toBe(56);
    await page.screenshot({ path: `dev/out/phase7-${w}-start.png` });
  });
}

test('a win on the live page: constellation aligned, fact and results shown', async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 812 });
  await open(page);
  const answer = await todaysAnswer(page);
  const wrong = { 4: 'STAR', 5: 'ORBIT', 6: 'PLANET', 7: 'PLANETS' }[answer.length];
  await play(page, [wrong === answer ? 'COMETS'.slice(0, answer.length) : wrong, answer]);
  await expect(page.locator('#spellar-root')).toHaveClass(/is-sky/, { timeout: 30_000 });
  await expect(page.locator('#spellar-root .sp-answer-word')).toHaveText(answer);
  await expect(page.locator('#spellar-root .sp-fact')).toHaveText(words.find((e) => e.word === answer).fact);
  const worst = await page.evaluate(() => {
    const rows = [...document.querySelectorAll('#spellar-root .sp-row')];
    return Math.max(...[...document.querySelectorAll('#spellar-root .sp-stars > g')].map((g, col) => {
      const r = g.getBoundingClientRect();
      const c = { x: r.left + r.width / 2, y: r.top + r.height / 2 };
      return Math.min(...rows.map((row) => { const t = row.children[col].getBoundingClientRect(); return Math.hypot(t.left + t.width / 2 - c.x, t.top + t.height / 2 - c.y); }));
    }));
  });
  expect(worst).toBeLessThan(0.75);
  await page.screenshot({ path: 'dev/out/phase7-375-win.png', fullPage: true });
});

test('the puzzle follows the player\'s date, not the cached page (date change by clock)', async ({ page }) => {
  const now = new Date();
  // Tomorrow in Toronto: still within a day of the server's date, so the API answers with puzzle +1.
  const tomorrow = new Date(now.getTime() + 24 * 3600 * 1000);
  await page.clock.install({ time: tomorrow });
  await open(page);
  const stored = await page.evaluate(() => JSON.parse(localStorage.getItem('spellar:v1')).puzzle);
  const expected = Object.keys(schedule.days).sort().indexOf(localDate(tomorrow)) + 1;
  expect(stored.number).toBe(expected);
  expect(stored.date).toBe(localDate(tomorrow));
});

test('at midnight the finished page moves on to the next puzzle', async ({ page }) => {
  // Finish today's puzzle just before midnight; the countdown reloads into the next day's.
  const today = localDate(new Date());
  const lateTonight = new Date(`${today}T23:58:00-04:00`);
  // Reduced motion (no tweens need the clock) and a paused clock while playing, so a slow server
  // cannot carry the time past midnight before the game is finished.
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.clock.install({ time: lateTonight });
  await open(page);
  await page.clock.pauseAt(new Date(lateTonight.getTime() + 90_000)); // 23:59:30, leaving time for a slow load
  const answer = schedule.days[today];
  await play(page, [answer]);
  await expect(page.locator('#spellar-root')).toHaveClass(/is-sky/, { timeout: 30_000 });
  await page.clock.runFor(70_000); // past midnight; the next countdown tick reloads the page
  await expect(page.locator('#spellar-root .sp-board')).toBeVisible({ timeout: 20_000 });
  await expect(page.locator('#spellar-root')).not.toHaveClass(/is-done/, { timeout: 60_000 });
  const stored = await page.evaluate(() => JSON.parse(localStorage.getItem('spellar:v1')).puzzle);
  expect(stored.date > today).toBe(true);
});

test.describe('menu dot (the "Spellar" menu item has the class spellar-menu-item)', () => {
  const today = new Date().toLocaleDateString('en-CA', { timeZone: 'America/Toronto' });
  const daysAgo = (n) => new Date(Date.parse(today) - n * 864e5).toISOString().slice(0, 10);
  const cases = [
    ['a new visitor sees it', null, true],
    ['day 3, not played today: shown', { firstVisit: daysAgo(2), lastPlayed: daysAgo(1) }, true],
    ['played today: never shown, not even for a moment', { firstVisit: daysAgo(1), lastPlayed: today }, false],
    ['more than 7 days after the first visit: never shown', { firstVisit: daysAgo(8) }, false],
  ];
  for (const [name, dot, shown] of cases) {
    test(name, async ({ page }) => {
      await page.addInitScript((dot) => {
        if (dot) localStorage.setItem('spellar:dot', JSON.stringify(dot));
        // Whether the dot's style rule was already in place when the menu item was first parsed.
        window.__dot = { styleAdded: 0, readyAtMenu: null };
        new MutationObserver((list) => {
          for (const m of list) for (const n of m.addedNodes) if (n.id === 'spellar-dot-style') window.__dot.styleAdded++;
          if (window.__dot.readyAtMenu === null && document.querySelector('.spellar-menu-item')) {
            window.__dot.readyAtMenu = Boolean(document.getElementById('spellar-dot-style'));
          }
        }).observe(document, { childList: true, subtree: true });
      }, dot);
      // The game page: its saved copy is renewed by every deploy, so it has the current dot script
      // (other pages' copies catch up within the page cache's 8 hours).
      await page.goto(PAGE, { waitUntil: 'domcontentloaded', timeout: 90_000 });
      await page.waitForTimeout(2000);
      expect(await page.locator('.spellar-menu-item').count()).toBeGreaterThan(0);
      const seen = await page.evaluate(() => window.__dot);
      expect(seen.styleAdded).toBe(shown ? 1 : 0);
      expect(seen.readyAtMenu).toBe(shown); // there from the menu's first paint, or never
      const after = await page.locator('.spellar-menu-item > a').first().evaluate((a) => {
        const s = getComputedStyle(a, '::after');
        return { content: s.content, width: s.width, height: s.height, bg: s.backgroundColor, radius: s.borderTopLeftRadius };
      });
      if (shown) expect(after).toEqual({ content: '""', width: '6px', height: '6px', bg: 'rgb(237, 40, 57)', radius: '50%' });
      else expect(after.content).toBe('none');
    });
  }
});
